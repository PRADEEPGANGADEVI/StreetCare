// Helper to strictly get only 100% completely Government-Verified NGOs
export function getGovtVerifiedNGOs() {
  return INITIAL_NGOS.filter((ngo) => ngo.isGovtVerified && ngo.status === 'Verified');
}

// LocalStorage Case Reports Management for real-time tracking
const STORAGE_KEY = 'streetcare_reports_v2';

export function getAllReports() {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved) {
      const parsed = JSON.parse(saved);
      // Merge unique reports
      const combined = [...parsed];
      INITIAL_REPORTS.forEach((initRep) => {
        if (!combined.some((r) => r.id === initRep.id)) {
          combined.push(initRep);
        }
      });
      return combined;
    }
  } catch (e) {
    console.error('Failed to load reports from storage:', e);
  }
  return INITIAL_REPORTS;
}

export function getReportById(caseId) {
  if (!caseId) return null;
  const reports = getAllReports();
  const normalized = caseId.trim().toUpperCase();
  return reports.find((r) => r.id.toUpperCase() === normalized) || null;
}

export function saveNewReport(reportData) {
  const currentReports = getAllReports();
  const updated = [reportData, ...currentReports.filter((r) => r.id !== reportData.id)];
  try {
    localStorage.setItem(STORAGE_KEY, JSON.stringify(updated));
  } catch (e) {
    console.error('Failed to persist report:', e);
  }
  return reportData;
}
